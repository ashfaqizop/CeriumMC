// Generates the java.lang.Character data that cerium-java needs, straight from the running JDK.
//
// Run with Java 25 (the JDK vanilla 26.3 ships with, Unicode 16.0) from the repository root:
//
//     java parity/tables/JdkCharData.java
//
// It writes:
// - crates/cerium-java/src/character/tables.rs: whitespace, digit values, Unicode blocks and
//   assigned code point ranges;
// - crates/cerium-java/src/character/names.bin: every explicit character name (the names
//   `Character.getName` returns that are not the "<block> <hex>" fallback), word-coded.
//
// names.bin layout (all integers big-endian):
//   u32 word count, then each word as u8 length + ASCII bytes;
//   u32 name count, then each name as u24 code point, u8 token count and that many u16
//   tokens. A token is a word index; bit 15 set means the separator before it is '-'
//   instead of ' ' (the first token has no separator and never sets the bit).
//
// The data is derived from the JDK (GPL-2.0 with Classpath Exception) and Unicode's
// UnicodeData.txt (Unicode License v3); it contains nothing from Mojang.

import java.io.ByteArrayOutputStream;
import java.io.DataOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

public class JdkCharData {
    public static void main(String[] args) throws IOException {
        Path dir = Path.of("crates/cerium-java/src/character");
        Files.createDirectories(dir);
        Files.writeString(dir.resolve("tables.rs"), tables(), StandardCharsets.UTF_8);
        Files.write(dir.resolve("names.bin"), names());
        System.out.println("java " + System.getProperty("java.version") + ", wrote " + dir);
    }

    /** A hex literal that Clippy's `unreadable_literal` accepts: 4-digit groups past 4 digits. */
    private static String hex(int value) {
        String digits = Integer.toHexString(value).toUpperCase(Locale.ROOT);
        if (digits.length() <= 4) {
            return "0x" + digits;
        }
        digits = "0".repeat((4 - digits.length() % 4) % 4) + digits;
        StringBuilder grouped = new StringBuilder("0x");
        for (int i = 0; i < digits.length(); i += 4) {
            if (i > 0) {
                grouped.append('_');
            }
            grouped.append(digits, i, i + 4);
        }
        return grouped.toString();
    }

    private static String fallbackName(int cp) {
        Character.UnicodeBlock block = Character.UnicodeBlock.of(cp);
        return block == null ? null
            : block.toString().replace('_', ' ') + " "
                + Integer.toHexString(cp).toUpperCase(Locale.ROOT);
    }

    private static String tables() {
        StringBuilder out = new StringBuilder();
        out.append("//! `java.lang.Character` data generated by `parity/tables/JdkCharData.java` from\n");
        out.append("//! Java ").append(System.getProperty("java.version"));
        out.append(" (Unicode 16.0). Do not edit by hand.\n\n");

        List<Integer> whitespace = new ArrayList<>();
        for (int c = 0; c <= 0xFFFF; c++) {
            if (Character.isWhitespace((char) c)) {
                whitespace.add(c);
            }
        }
        out.append("/// Every `char` for which `Character.isWhitespace(char)` is true.\n");
        out.append("#[rustfmt::skip]\n");
        out.append("pub(super) static WHITESPACE: [u16; ").append(whitespace.size()).append("] = [\n");
        for (int c : whitespace) {
            out.append(String.format("    0x%04X,\n", c));
        }
        out.append("];\n\n");

        // Runs of consecutive chars whose Character.digit(ch, 36) values are consecutive.
        List<int[]> digits = new ArrayList<>();
        int[] run = null;
        for (int c = 0; c <= 0xFFFF; c++) {
            int d = Character.digit((char) c, 36);
            if (d < 0) {
                run = null;
                continue;
            }
            if (run != null && run[1] == c - 1 && run[2] + (c - run[0]) == d) {
                run[1] = c;
            } else {
                run = new int[] {c, c, d};
                digits.add(run);
            }
        }
        out.append("/// `Character.digit(ch, 36)` for every `char` that has a digit value, as runs of\n");
        out.append("/// `(first, last, value of first)` whose values increase by one per `char`.\n");
        out.append("pub(super) static DIGITS: [(u16, u16, u8); ").append(digits.size()).append("] = [\n");
        for (int[] r : digits) {
            out.append(String.format("    (0x%04X, 0x%04X, %d),\n", r[0], r[1], r[2]));
        }
        out.append("];\n\n");

        List<Object[]> blocks = new ArrayList<>();
        Object[] current = null;
        for (int cp = 0; cp <= Character.MAX_CODE_POINT; cp++) {
            Character.UnicodeBlock block = Character.UnicodeBlock.of(cp);
            if (block == null) {
                current = null;
                continue;
            }
            String name = block.toString().replace('_', ' ');
            if (current != null && current[2].equals(name) && (int) current[1] == cp - 1) {
                current[1] = cp;
            } else {
                current = new Object[] {cp, cp, name};
                blocks.add(current);
            }
        }
        out.append("/// `Character.UnicodeBlock.of` as `(first, last, name)`, where `name` is the block's\n");
        out.append("/// `toString()` with underscores replaced by spaces (as `Character.getName` uses it).\n");
        out.append("pub(super) static BLOCKS: [(u32, u32, &str); ").append(blocks.size()).append("] = [\n");
        for (Object[] b : blocks) {
            String inner = hex((int) b[0]) + ", " + hex((int) b[1]) + ", \"" + b[2] + "\"";
            String entry = "    (" + inner + "),";
            if (inner.length() > 60) {
                // rustfmt's layout for a tuple whose items exceed its 60-column width.
                entry = "    (\n        " + hex((int) b[0]) + ",\n        " + hex((int) b[1])
                    + ",\n        \"" + b[2] + "\",\n    ),";
            }
            out.append(entry).append('\n');
        }
        out.append("];\n\n");

        List<int[]> assigned = new ArrayList<>();
        int[] range = null;
        for (int cp = 0; cp <= Character.MAX_CODE_POINT; cp++) {
            if (Character.getType(cp) == Character.UNASSIGNED) {
                range = null;
            } else if (range != null) {
                range[1] = cp;
            } else {
                range = new int[] {cp, cp};
                assigned.add(range);
            }
        }
        out.append("/// The code points whose `Character.getType` is not `UNASSIGNED`, as inclusive ranges.\n");
        out.append("pub(super) static ASSIGNED: [(u32, u32); ").append(assigned.size()).append("] = [\n");
        for (int[] r : assigned) {
            out.append("    (" + hex(r[0]) + ", " + hex(r[1]) + "),\n");
        }
        out.append("];\n");
        return out.toString();
    }

    private static byte[] names() throws IOException {
        Map<String, Integer> wordIndex = new HashMap<>();
        List<String> words = new ArrayList<>();
        List<Integer> codePoints = new ArrayList<>();
        List<int[]> tokens = new ArrayList<>();
        for (int cp = 0; cp <= Character.MAX_CODE_POINT; cp++) {
            String name = Character.getName(cp);
            if (name == null || name.equals(fallbackName(cp))) {
                continue;
            }
            List<Integer> encoded = new ArrayList<>();
            int start = 0;
            boolean hyphen = false;
            for (int i = 0; i <= name.length(); i++) {
                if (i == name.length() || name.charAt(i) == ' ' || name.charAt(i) == '-') {
                    String word = name.substring(start, i);
                    Integer index = wordIndex.get(word);
                    if (index == null) {
                        index = words.size();
                        wordIndex.put(word, index);
                        words.add(word);
                    }
                    encoded.add(index | (hyphen ? 0x8000 : 0));
                    if (i < name.length()) {
                        hyphen = name.charAt(i) == '-';
                    }
                    start = i + 1;
                }
            }
            if (words.size() >= 0x8000 || encoded.size() > 0xFF) {
                throw new IllegalStateException("name does not fit the format: " + name);
            }
            codePoints.add(cp);
            tokens.add(encoded.stream().mapToInt(Integer::intValue).toArray());
        }

        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        DataOutputStream out = new DataOutputStream(bytes);
        out.writeInt(words.size());
        for (String word : words) {
            byte[] ascii = word.getBytes(StandardCharsets.US_ASCII);
            out.writeByte(ascii.length);
            out.write(ascii);
        }
        out.writeInt(codePoints.size());
        for (int i = 0; i < codePoints.size(); i++) {
            int cp = codePoints.get(i);
            out.writeByte(cp >> 16);
            out.writeShort(cp & 0xFFFF);
            int[] t = tokens.get(i);
            out.writeByte(t.length);
            for (int token : t) {
                out.writeShort(token);
            }
        }
        out.flush();
        return bytes.toByteArray();
    }
}
