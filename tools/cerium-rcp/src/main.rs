//! `cerium-rcp` measures this CPU's `RCPPS` instruction exactly.
//!
//! HotSpot's x86_64 `Math.log`, `log10` and `pow` start from `RCPPS`, an approximate
//! reciprocal whose exact output differs between CPU vendors. That is why vanilla's
//! `Math.pow` differs between Intel and AMD servers. Every call site feeds it a float `1.m`,
//! built from the top 23 mantissa bits of the argument, so this tool evaluates `RCPPS` on all
//! 2^23 such inputs and writes the result as an exact run-length table. CeriumMC embeds one
//! table per vendor.
//!
//! Usage: `cerium-rcp OUTPUT.rs`

use std::fmt::Write as _;

/// Number of distinct `1.m` inputs: one per 23-bit mantissa.
const INPUTS: u32 = 1 << 23;

fn main() {
    let Some(path) = std::env::args().nth(1) else {
        eprintln!("usage: cerium-rcp OUTPUT.rs");
        std::process::exit(2);
    };
    if let Some(measurement) = x86::measure() {
        print!("{}", measurement.summary());
        std::fs::write(&path, measurement.to_rust()).expect("cannot write the table");
    } else {
        eprintln!("RCPPS exists only on x86_64");
        std::process::exit(1);
    }
}

/// One maximal run of equal outputs: inputs `start..next start` all give `bits`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct Run {
    start: u32,
    bits: u32,
}

/// The measured `RCPPS` function over all `1.m` inputs.
#[derive(Debug)]
struct Measurement {
    vendor: String,
    brand: String,
    runs: Vec<Run>,
    digest: u64,
    monotonic: bool,
}

impl Measurement {
    fn from_outputs(vendor: String, brand: String, outputs: impl Iterator<Item = u32>) -> Self {
        let mut runs: Vec<Run> = Vec::new();
        let mut digest: u64 = 0xCBF2_9CE4_8422_2325;
        let mut monotonic = true;
        let mut previous = u32::MAX;
        for (start, bits) in (0..INPUTS).zip(outputs) {
            for byte in bits.to_le_bytes() {
                digest = (digest ^ u64::from(byte)).wrapping_mul(0x0100_0000_01B3);
            }
            if bits > previous {
                monotonic = false;
            }
            previous = bits;
            if runs.last().is_none_or(|run| run.bits != bits) {
                runs.push(Run { start, bits });
            }
        }
        Self {
            vendor,
            brand,
            runs,
            digest,
            monotonic,
        }
    }

    fn summary(&self) -> String {
        format!(
            "vendor: {}\nbrand: {}\nruns: {}\nmonotonic: {}\ndigest: {:016x}\n",
            self.vendor,
            self.brand,
            self.runs.len(),
            self.monotonic,
            self.digest
        )
    }

    fn to_rust(&self) -> String {
        let mut out = String::new();
        let _ = writeln!(
            out,
            "//! Generated by `cerium-rcp` on {} (`{}`).",
            self.brand, self.vendor
        );
        let _ = writeln!(
            out,
            "//! Do not edit by hand. Digest: {:016x}.",
            self.digest
        );
        let _ = writeln!(out, "//!");
        let _ = writeln!(
            out,
            "//! `RCPPS(1.m)` for every 23-bit mantissa `m`, as runs of equal output:"
        );
        let _ = writeln!(
            out,
            "//! each `(start, bits)` covers mantissas from `start` to the next start."
        );
        out.push('\n');
        let _ = writeln!(out, "#[rustfmt::skip]");
        let _ = writeln!(
            out,
            "pub(crate) static RUNS: [(u32, u32); {}] = [",
            self.runs.len()
        );
        for run in &self.runs {
            let start = run.start;
            let bits = run.bits;
            let _ = writeln!(
                out,
                "    (0x{:02X}_{:04X}, 0x{:04X}_{:04X}),",
                start >> 16,
                start & 0xFFFF,
                bits >> 16,
                bits & 0xFFFF
            );
        }
        out.push_str("];\n");
        out
    }
}

#[cfg(target_arch = "x86_64")]
mod x86 {
    use std::arch::x86_64::{__cpuid, _mm_cvtss_f32, _mm_rcp_ps, _mm_set1_ps};

    use super::{INPUTS, Measurement};

    /// `RCPPS` on one value.
    #[allow(
        unsafe_code,
        unused_unsafe,
        reason = "SSE is part of the x86_64 baseline"
    )]
    fn rcp(x: f32) -> f32 {
        // SAFETY: SSE is always available on x86_64, and the intrinsic has no preconditions.
        unsafe { _mm_cvtss_f32(_mm_rcp_ps(_mm_set1_ps(x))) }
    }

    /// The CPUID vendor and brand strings.
    #[allow(
        unsafe_code,
        unused_unsafe,
        reason = "CPUID is always available on x86_64"
    )]
    fn cpu_names() -> (String, String) {
        // SAFETY: CPUID exists on every x86_64 CPU; leaves 0 and 0x8000_0002..=4 are standard.
        let (vendor_regs, brand_regs) = unsafe {
            let leaf0 = __cpuid(0);
            let brand: Vec<_> = (0x8000_0002..=0x8000_0004).map(__cpuid).collect();
            (leaf0, brand)
        };
        let mut vendor = Vec::new();
        for reg in [vendor_regs.ebx, vendor_regs.edx, vendor_regs.ecx] {
            vendor.extend_from_slice(&reg.to_le_bytes());
        }
        let mut brand = Vec::new();
        for regs in brand_regs {
            for reg in [regs.eax, regs.ebx, regs.ecx, regs.edx] {
                brand.extend_from_slice(&reg.to_le_bytes());
            }
        }
        let text = |bytes: Vec<u8>| {
            String::from_utf8_lossy(&bytes)
                .trim_matches(char::from(0))
                .trim()
                .to_owned()
        };
        (text(vendor), text(brand))
    }

    #[allow(
        clippy::unnecessary_wraps,
        reason = "the signature is shared with the non-x86 fallback"
    )]
    pub(super) fn measure() -> Option<Measurement> {
        let (vendor, brand) = cpu_names();
        let outputs = (0..INPUTS).map(|m| rcp(f32::from_bits(0x3F80_0000 | m)).to_bits());
        Some(Measurement::from_outputs(vendor, brand, outputs))
    }
}

#[cfg(not(target_arch = "x86_64"))]
mod x86 {
    use super::Measurement;

    pub(super) fn measure() -> Option<Measurement> {
        None
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn runs_merge_equal_neighbours() {
        let outputs = (0..INPUTS).map(|m| if m < 10 { 7 } else { 5 });
        let measurement = Measurement::from_outputs(String::new(), String::new(), outputs);
        assert_eq!(
            measurement.runs,
            [Run { start: 0, bits: 7 }, Run { start: 10, bits: 5 }]
        );
        assert!(measurement.monotonic);
    }
}
